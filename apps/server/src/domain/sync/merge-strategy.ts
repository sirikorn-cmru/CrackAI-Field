import type { SurveyedBuildingSyncState } from '@crackai/shared';

/**
 * กลยุทธ์ merge อัตโนมัติก่อนตัดสินว่า "merge ไม่ได้" — NFR-03 (T-1-08)
 *
 * ผู้ใช้ตัดสินเมื่อ 2026-09-04 ว่า Phase 1 ใช้ `manualOnlyMergeStrategy` — ส่งให้มนุษย์ตัดสินใจ
 * ทุกครั้งที่พบความขัดแย้ง ไม่ทำ auto-merge ระดับฟิลด์ (db-spec §11, api-spec §16 ปิดแล้ว)
 *
 * คงไว้เป็น port แทนการเขียนตายลงไปในบริการ เพราะเอกสารบันทึกไว้ว่า NFR-03 ยังรองรับเพียง
 * บางส่วนในเฟสนี้ และส่วนที่เหลือจะถูกเติมด้วยการเพิ่มกลยุทธ์อีกตัวที่นี่ ไม่ใช่การรื้อ
 * `SyncIntakeService`
 */
export interface MergeCandidate {
  /** ค่าที่เซิร์ฟเวอร์ถืออยู่ตอนนี้ */
  current: SurveyedBuildingSyncState;
  currentSnapshot: string;
  /** ค่าที่อุปกรณ์ส่งเข้ามา */
  incomingSnapshot: string;
  incomingDeviceId: string;
  incomingDataVersion: number;
  incomingLastModifiedAt: Date;
}

export interface MergeStrategy {
  /** ชื่อกลยุทธ์ — บันทึกลง audit trail เพื่อให้ตรวจย้อนหลังได้ว่าใช้กติกาใดตอนนั้น */
  readonly name: string;
  /** คืน snapshot ที่ merge แล้ว หรือ `null` เมื่อ merge อัตโนมัติไม่ได้ (ส่งต่อให้มนุษย์) */
  tryMerge(candidate: MergeCandidate): Promise<string | null>;
}

/**
 * กลยุทธ์ที่ผู้ใช้ตัดสินใจเลือกเมื่อ 2026-09-04: ส่งให้มนุษย์ตัดสินใจทุกครั้งที่พบความขัดแย้ง
 * ไม่ทำ auto-merge ระดับฟิลด์ใน Phase 1 (db-spec §11, architecture §6.9)
 *
 * **รู้ไว้ก่อนแก้ไฟล์นี้: กลยุทธ์นี้ทำให้ NFR-03 รองรับเพียงบางส่วนโดยเจตนา**
 * NFR-03 กำหนดให้ "รวมข้อมูลอัตโนมัติเมื่อไม่ขัดแย้งกัน" แต่การตรวจจับของระบบอยู่ที่ระดับ
 * aggregate เท่านั้น (ดู `isConflicting()` ใน sync-intake.service.ts) — สองอุปกรณ์ที่แก้
 * **คนละฟิลด์** ของอาคารเดียวกันจึงถูกส่งให้มนุษย์ ทั้งที่ในทางทฤษฎี merge ได้
 *
 * เหตุผลที่ยอมรับ: ข้อมูลความเสียหายอาคารมีผลต่อความปลอดภัยของคน การ merge ผิดเงียบๆ แล้ว
 * ไม่มีใครรู้คือความเสี่ยงที่ไม่คุ้มกับการประหยัดแรงคน และยังไม่มีข้อมูลจริงว่าอาคารหลังเดียว
 * ถูกสำรวจพร้อมกันสองทีมบ่อยแค่ไหน — สร้างกลไกซับซ้อนก่อนรู้ว่าจำเป็นคือการเดา
 *
 * เงื่อนไขที่จะทำให้กลับมาทำส่วนที่เหลือ: พบว่าคิวแก้ด้วยมือยาวเกินรับไหว หรือพบว่าการแก้
 * คนละฟิลด์พร้อมกันเกิดบ่อยจริง — ตอนนั้นเพิ่มกลยุทธ์อีกตัวแล้วเปลี่ยนที่จุดประกอบระบบจุดเดียว
 */
export const manualOnlyMergeStrategy: MergeStrategy = {
  name: 'ส่งให้มนุษย์ตัดสินใจทุกครั้ง',
  tryMerge: async () => null,
};
